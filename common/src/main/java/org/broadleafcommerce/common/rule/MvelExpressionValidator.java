package org.broadleafcommerce.common.rule;

import org.apache.commons.logging.Log;
import org.apache.commons.logging.LogFactory;
import org.broadleafcommerce.common.util.StringUtil;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

import java.util.Arrays;
import java.util.Collections;
import java.util.HashSet;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Validates MVEL rule expressions before they are saved and before {@link MvelHelper} compiles them. MVEL has no
 * sandbox of its own, so an expression is rejected if it uses {@code new}, a reflection method
 * ({@link #BLOCKED_REFLECTION_METHODS}), a method that can run commands or change the server or its data
 * ({@link #BLOCKED_METHODS}), or a statement separator ({@code ;}). Methods are
 * blocked whether they are called with parentheses or accessed like a property, since MVEL calls no argument methods
 * for both.
 * <p>
 * {@code MVEL.eval} can evaluate any expression, so only the legacy {@code MVEL.eval("toUpperCase()", value)} form
 * generated by older versions of the rule builder is allowed.
 * <p>
 * String literals are removed before the check, read the same way MVEL reads them, so their contents are never
 * mistaken for code.
 * <p>
 * The validation can be turned off with the {@code mvel.expression.validation.enabled} property. Methods can be
 * blocked in addition to the built-in ones with the {@code mvel.expression.validation.blocked.methods} property, and
 * built-in ones can be allowed with the {@code mvel.expression.validation.allowed.methods} property, e.g. for custom
 * fields with the same name as a blocked method. This class is a bean only so that the properties can be injected.
 */
@Component("blMvelExpressionValidator")
public class MvelExpressionValidator {

    private static final Log LOG = LogFactory.getLog(MvelExpressionValidator.class);

    // true unless turned off by the property, including when there is no application context, e.g. in unit tests
    private static volatile boolean enabled = true;
    // set from the mvel.expression.validation.blocked.methods and allowed.methods properties, empty by default
    private static volatile Set<String> additionalBlockedMethods = Collections.emptySet();
    private static volatile Set<String> allowedMethods = Collections.emptySet();

    private static final String NEW_KEYWORD = "new";
    private static final String STATEMENT_SEPARATOR = ";";

    private static final Set<String> BLOCKED_REFLECTION_METHODS = new HashSet<>(Arrays.asList(
            "getClass", "forName", "getMethod", "getMethods", "getDeclaredMethod", "getDeclaredMethods",
            "getField", "getFields", "getDeclaredField", "getDeclaredFields", "getConstructor", "getConstructors",
            "getDeclaredConstructor", "getDeclaredConstructors", "newInstance", "invoke", "setAccessible",
            "getClassLoader", "getContextClassLoader", "loadClass",
            // creates an instance of any class by name without using new, e.g. java.beans.Beans.instantiate
            "instantiate"
    ));

    private static final Set<String> BLOCKED_METHODS = new HashSet<>(Arrays.asList(
            // operating system commands and JVM state
            "getRuntime", "exec", "halt", "exit", "getenv", "getProperty", "setProperty", "currentThread", "sleep",
            // loading classes or native code, e.g. java.util.ServiceLoader.load, System.load, System.loadLibrary
            "load", "loadLibrary",
            // killing processes, e.g. java.lang.ProcessHandle
            "destroy", "destroyForcibly",
            // file system and JNDI
            "readAllLines", "readAllBytes", "readString", "write", "writeString", "delete", "doLookup", "lookup",
            // evaluating other expressions, e.g. org.mvel2.MVEL and org.mvel2.templates
            "eval", "evalToString", "evalFile", "compileExpression", "executeExpression", "compileSetExpression",
            "executeSetExpression", "executeAllExpression", "evaluateRule",
            // database access and changing data
            "getHibernateLazyInitializer", "getSession", "createNativeQuery", "clear"
    ));

    // a backslash escapes the next character, as in org.mvel2.util.ParseTools#captureStringLiteral
    private static final Pattern STRING_LITERAL = Pattern.compile(
            "\"[^\"\\\\]*+(?:\\\\.[^\"\\\\]*+)*+\"|'[^'\\\\]*+(?:\\\\.[^'\\\\]*+)*+'", Pattern.DOTALL);
    private static final String LEGACY_EVAL_ARGUMENT = "toUpperCase()";
    private static final String LEGACY_EVAL_ARGUMENT_MARKER = " #LEGACY_EVAL_ARGUMENT# ";
    private static final Pattern LEGACY_MVEL_EVAL = Pattern.compile(
            "\\bMVEL\\s*+\\.\\s*+eval\\s*+\\(\\s*+" + LEGACY_EVAL_ARGUMENT_MARKER.trim() + "\\s*+,");
    private static final Pattern IDENTIFIER = Pattern.compile(
            "\\p{javaJavaIdentifierStart}\\p{javaJavaIdentifierPart}*+");

    protected MvelExpressionValidator() {
    }

    @Value("${mvel.expression.validation.enabled:true}")
    public void setEnabled(boolean enabled) {
        MvelExpressionValidator.enabled = enabled;
    }

    /**
     * @param blockedMethods comma separated method names to block in addition to the built-in ones
     */
    @Value("${mvel.expression.validation.blocked.methods:}")
    public void setBlockedMethods(String blockedMethods) {
        additionalBlockedMethods = splitNames(blockedMethods);
    }

    /**
     * @param allowedMethods comma separated built-in blocked method names to allow, e.g. for custom fields that have
     *                       the same name as a blocked method
     */
    @Value("${mvel.expression.validation.allowed.methods:}")
    public void setAllowedMethods(String allowedMethods) {
        MvelExpressionValidator.allowedMethods = splitNames(allowedMethods);
        if (!MvelExpressionValidator.allowedMethods.isEmpty()) {
            LOG.warn("The following methods are allowed in mvel rule expressions although they are blocked by default: "
                    + MvelExpressionValidator.allowedMethods);
        }
    }

    private static Set<String> splitNames(String names) {
        Set<String> response = new HashSet<>();
        if (names != null) {
            for (String name : names.split(",")) {
                if (!name.trim().isEmpty()) {
                    response.add(name.trim());
                }
            }
        }
        return Collections.unmodifiableSet(response);
    }

    private static boolean isBlockedMethod(String name) {
        boolean blocked = BLOCKED_REFLECTION_METHODS.contains(name) || BLOCKED_METHODS.contains(name)
                || additionalBlockedMethods.contains(name);
        return blocked && !allowedMethods.contains(name);
    }

    /**
     * Checks the expression and logs a warning if it is not allowed. A null expression is allowed, the same as an empty
     * one, since there is no rule.
     *
     * @param expression the MVEL expression exactly as it will be compiled
     * @return true if the expression may be compiled and executed
     */
    public static boolean isAllowed(String expression) {
        if (!enabled || expression == null) {
            return true;
        }
        boolean allowed = isValid(expression);
        if (!allowed) {
            LOG.warn("The mvel expression (" + StringUtil.sanitize(expression) + ") is not allowed, since it uses new,"
                    + " reflection, a blocked method or a statement separator");
        }
        return allowed;
    }

    private static boolean isValid(String expression) {
        String code = STRING_LITERAL.matcher(expression).replaceAll(literal -> {
            String content = literal.group().substring(1, literal.group().length() - 1);
            return LEGACY_EVAL_ARGUMENT.equals(content) ? LEGACY_EVAL_ARGUMENT_MARKER : " ";
        });
        // a quote left over is an unterminated string literal, and MVEL skips comments, either of which could
        // otherwise hide code from this check
        if (code.contains("\"") || code.contains("'") || code.contains("//") || code.contains("/*")) {
            return false;
        }
        // a rule is a single expression, so a statement separator can only be used to add more statements
        if (code.contains(STATEMENT_SEPARATOR)) {
            return false;
        }
        code = LEGACY_MVEL_EVAL.matcher(code).replaceAll(" ");

        Matcher identifiers = IDENTIFIER.matcher(code);
        while (identifiers.find()) {
            String name = identifiers.group();
            if (NEW_KEYWORD.equals(name) || isBlockedMethod(name)) {
                return false;
            }
        }
        return true;
    }

}
