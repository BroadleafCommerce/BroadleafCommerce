package org.broadleafcommerce.test.common.rule;

import org.broadleafcommerce.common.rule.MvelExpressionValidator;
import org.springframework.context.annotation.AnnotationConfigApplicationContext;
import org.springframework.core.env.MapPropertySource;

import java.util.Collections;

import junit.framework.TestCase;

public class MvelExpressionValidatorTest extends TestCase {

    /**
     * Expressions generated by the rule builder, including legacy forms, and hand written rules from the tests and
     * demo data must remain allowed.
     */
    public void testRuleBuilderExpressionsAreAllowed() {
        assertAllowed("MvelHelper.toUpperCase(?discreteOrderItem.?category.?name)==MvelHelper.toUpperCase(\"merchandise\")");
        assertAllowed("!(?discreteOrderItem.?product.?manufacturer==\"test manufacturer\")");
        assertAllowed("?fulfillmentGroup.?address.?stateProvinceRegion==\"Texas\"&&(?fulfillmentGroup.?retailFulfillmentPrice.getAmount()>=99&&(?fulfillmentGroup.?retailFulfillmentPrice.getAmount()<=199))");
        assertAllowed("CollectionUtils.intersection(?discreteOrderItem.?category.?name,[\"test category\", \"test category 2\"]).size()>0");
        assertAllowed("(MvelHelper.convertField(\"DATE\",?customer.?getCustomerAttributes()[\"invoice_date\"])"
                + ">MvelHelper.convertField(\"DATE\",MvelHelper.subtractFromCurrentTime(12))"
                + "&&(MvelHelper.convertField(\"DATE\",?customer.?getCustomerAttributes()[\"invoice_date\"])"
                + "<MvelHelper.convertField(\"DATE\",MvelHelper.currentTime())))");
        assertAllowed("?customer.?getCustomerAttributes().?get(\"invoice_date\").?value==\"x\"");
        assertAllowed("?customer.?getCustomerAttributes().?get(\"invoice_date\").?getValue()==\"x\"");
        assertAllowed("org.apache.commons.lang3.StringUtils.contains(?customer.?emailAddress,\"@test.com\")");
        assertAllowed("([1,2] contains ?customer.?id.intValue())");
        assertAllowed("?time.?hour.getType()>9&&(?time.?hour.getType()<17)");
        assertAllowed("order.?getPriceBeforeAdjustments(true).getAmount() > 10.5");
        assertAllowed("MVEL.eval(\"toUpperCase()\",discreteOrderItem.?category.?name)==MVEL.eval(\"toUpperCase()\",\"merchandise\")");
        assertAllowed("([MVEL.eval(\"toUpperCase()\",\"test1\"), MVEL.eval(\"toUpperCase()\",\"test2\")] contains MVEL.eval(\"toUpperCase()\", discreteOrderItem.category.name))");
        assertAllowed("orderItem.?product.?dateCreated>java.text.DateFormat.getDateTimeInstance(3,3).parse(\"01/01/2020 12:00 AM\")");
        assertAllowed("locale.localeCode == 'US'");
        assertAllowed("request.properties['blcSearchTerm'] == 'hot'");
    }

    /**
     * String literal contents are data and must never be treated as code.
     */
    public void testNullAndEmptyExpressionsAreAllowed() {
        assertAllowed(null);
        assertAllowed("");
        assertAllowed("   ");
    }

    public void testCodeInsideStringLiteralsIsAllowed() {
        assertAllowed("?customer.?emailAddress==\"x\\\"+Runtime.getRuntime().exec(\\\"id\\\")+\\\"y\"");
        assertAllowed("?customer.?firstName=='new System.exit(0) // getClass()'");
    }

    /**
     * Product, sku and other names containing "new" are values in string literals, or part of a longer name, and
     * must not be mistaken for the new keyword.
     */
    public void testNewInsideValuesAndNamesIsAllowed() {
        assertAllowed("?product.?name==\"new\"");
        assertAllowed("?product.?name==\"New Arrivals\"");
        assertAllowed("?sku.?name=='new sku'");
        assertAllowed("MvelHelper.toUpperCase(?sku.?name)==MvelHelper.toUpperCase(\"brand new\")");
        assertAllowed("org.apache.commons.lang3.StringUtils.contains(?product.?name,\"new\")");
        assertAllowed("CollectionUtils.intersection(?product.?name,[\"new\",\"newest\"]).size()>0");
        assertAllowed("([\"new\",\"used\"] contains ?sku.?name)");
        assertAllowed("?product.?getProductAttributes()[\"new\"]==\"true\"");
        assertAllowed("?product.?getProductAttributes().?get(\"new\").?value==\"new\"");
        assertAllowed("?product.?newArrival==true && ?customer.?renewalDate!=null");
    }

    public void testReportedPayloadIsRejected() {
        assertRejected("?customer.?emailAddress==\"x\"+Runtime.getRuntime().exec(new String[]{\"/bin/sh\",\"-c\",\"id > /tmp/broadleaf_http_rce.txt\"})+\"y\"");
        assertRejected("?customer.?emailAddress==\"x\"+Runtime.getRuntime().exec(\"id\")+\"y\"");
    }

    public void testConstructorsAreRejected() {
        assertRejected("new java.io.File(\"/tmp\") != null");
        assertRejected("customer.emailAddress == new String(\"x\")");
        assertRejected("new ProcessBuilder(\"sh\") != null");
        assertRejected("(new\tjava.lang.StringBuilder(\"x\")) != null");
        assertRejected("new java.lang.String[]{\"a\"} != null");
    }

    /**
     * Factory methods that create or load classes without using new
     */
    public void testObjectCreationWithoutNewIsRejected() {
        assertRejected("java.beans.Beans.instantiate(null, \"java.lang.StringBuilder\") != null");
        assertRejected("java.util.ServiceLoader.load(java.lang.Runnable) != null");
        assertRejected("java.lang.System.load(\"/tmp/lib.so\") == null");
        assertRejected("java.lang.System.loadLibrary(\"lib\") == null");
        assertRejected("java.lang.ProcessHandle.current().destroy()");
        assertRejected("java.lang.ProcessHandle.of(1).get().destroyForcibly()");
    }

    public void testReflectionIsRejected() {
        assertRejected("customer.getClass() != null");
        assertRejected("customer.?getClass() != null");
        assertRejected("\"\".getClass() != null");
        assertRejected("1.getClass() != null");
        assertRejected("MvelHelper.toUpperCase(\"a\").getClass() != null");
        assertRejected("Class.forName(\"java.lang.System\") != null");
        assertRejected("customer.class.forName(\"java.lang.System\") != null");
        assertRejected("customer.emailAddress.class.getMethod(\"length\").invoke(\"a\") != null");
        assertRejected("customer.class.getDeclaredMethod(\"x\") != null");
        assertRejected("customer.class.getDeclaredField(\"password\") != null");
        assertRejected("customer.class.getField(\"x\") != null");
        assertRejected("customer.class.getConstructor() != null");
        assertRejected("customer.class.newInstance() != null");
        assertRejected("customer.class.declaredFields[0].setAccessible(true) == null");
        assertRejected("customer.class.getClassLoader().loadClass(\"x\") != null");
        assertRejected("Thread.currentThread().getContextClassLoader() != null");
    }

    public void testBlockedMethodsAreRejected() {
        assertRejected("System.setProperty(\"a\",\"1\") != null");
        assertRejected("java.lang.Runtime.getRuntime().halt(0) == null");
        assertRejected("System.getenv() != null");
        assertRejected("System.getProperty(\"user.home\") != null");
        assertRejected("Thread.sleep(100000) == null");
        assertRejected("java.nio.file.Files.readAllLines(customer.path) != null");
        assertRejected("java.nio.file.Files.delete(customer.path) == null");
        assertRejected("javax.naming.InitialContext.doLookup(\"ldap://x\") != null");
        assertRejected("MVEL.eval(\"System.exit(0)\") == null");
        assertRejected("MVEL.eval('Runtime.getRuntime()',customer) == null");
        assertRejected("MVEL.eval(\"toUpperCase()\"+\"x\",customer) == null");
        assertRejected("MvelHelper.evaluateRule(\"true\",null)");
        assertRejected("customer.getHibernateLazyInitializer().getSession() != null");
        assertRejected("customer.session.createNativeQuery(\"delete from BLC_ORDER\") != null");
        assertRejected("order.orderItems.clear() == null");
        assertRejected("customer.{ orderItems.clear() } != null");
    }

    public void testStatementSeparatorsAreRejected() {
        assertRejected("customer.emailAddress == \"x\"; true");
        assertRejected("customer.emailAddress = \"x\"; customer.emailAddress == \"x\"");
        assertRejected("def f() { true }; f()");
        assertAllowed("?customer.?emailAddress == \"a;b\"");
        assertAllowed("?customer.?firstName == 'x; y'");
    }

    /**
     * MVEL calls no argument methods written as properties, so blocked methods must be blocked in that form too.
     */
    public void testBlockedMethodsWithoutParenthesesAreRejected() {
        assertRejected("order.orderItems.clear == null");
        assertRejected("Thread.currentThread != null");
    }

    /**
     * The validator must agree with MVEL on where string literals and comments start and end.
     */
    public void testCodeHiddenFromTheValidatorIsRejected() {
        assertRejected("?customer.?emailAddress==\"x\\\\\"+System.setProperty(\"a\",\"1\")+\"\"");
        assertRejected("customer.emailAddress == 'x' //\"\nSystem.exit(0) //\"");
        assertRejected("customer.emailAddress == 'x' /*\"*/ System.exit(0) /*\"*/");
        assertRejected("customer.emailAddress == \"x");
        assertRejected("customer.emailAddress == 'x");
    }

    /**
     * Long string values, with or without escapes, must not overflow the stack while being removed.
     */
    public void testLongStringLiteralsAreAllowed() {
        StringBuilder value = new StringBuilder();
        for (int i = 0; i < 100000; i++) {
            value.append("ab\\\"");
        }
        assertAllowed("?customer.?emailAddress==\"" + value + "\"");
        assertAllowed("?customer.?emailAddress=='" + value + "'");
    }

    public void testValidationIsEnabledByDefault() {
        String payload = "Runtime.getRuntime().exec(\"id\") != null";
        assertFalse(isAllowedWithProperty(null, null, payload));
        assertFalse(isAllowedWithProperty("mvel.expression.validation.enabled", "true", payload));
    }

    public void testValidationCanBeTurnedOffWithProperty() {
        assertTrue(isAllowedWithProperty("mvel.expression.validation.enabled", "false",
                "Runtime.getRuntime().exec(\"id\") != null"));
    }

    public void testMethodsCanBeBlockedWithProperty() {
        String rule = "customer.emailAddress.toLowerCase() == \"x\"";
        assertTrue(isAllowedWithProperty(null, null, rule));
        assertFalse(isAllowedWithProperty("mvel.expression.validation.blocked.methods", " getDataSource, toLowerCase ", rule));
    }

    /**
     * Allowing a built-in blocked method allows only that method, e.g. for a custom field called load
     */
    public void testBuiltInMethodsCanBeAllowedWithProperty() {
        String allowedMethods = "mvel.expression.validation.allowed.methods";
        assertFalse(isAllowedWithProperty(null, null, "?product.?load > 5"));
        assertTrue(isAllowedWithProperty(allowedMethods, "load", "?product.?load > 5"));
        assertFalse(isAllowedWithProperty(allowedMethods, "load", "Runtime.getRuntime().exec(\"id\") != null"));
        assertFalse(isAllowedWithProperty(allowedMethods, "load", "new java.io.File(\"/tmp\") != null"));
        assertFalse(isAllowedWithProperty(allowedMethods, "load", "?product.?load > 5; true"));
    }

    /**
     * Starts a Spring context with the given property, so that the properties are injected the way they are in an
     * application, and resets them afterwards
     */
    private boolean isAllowedWithProperty(String property, String value, String expression) {
        AnnotationConfigApplicationContext context = new AnnotationConfigApplicationContext();
        try {
            if (property != null) {
                context.getEnvironment().getPropertySources().addFirst(new MapPropertySource("test",
                        Collections.singletonMap(property, value)));
            }
            context.register(MvelExpressionValidator.class);
            context.refresh();
            return MvelExpressionValidator.isAllowed(expression);
        } finally {
            MvelExpressionValidator validator = context.getBean(MvelExpressionValidator.class);
            validator.setEnabled(true);
            validator.setBlockedMethods("");
            validator.setAllowedMethods("");
            context.close();
        }
    }

    private void assertAllowed(String expression) {
        assertTrue("Expected to be allowed: " + expression, MvelExpressionValidator.isAllowed(expression));
    }

    private void assertRejected(String expression) {
        assertFalse("Expected to be rejected: " + expression, MvelExpressionValidator.isAllowed(expression));
    }

}
